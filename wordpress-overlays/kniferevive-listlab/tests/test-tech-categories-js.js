const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname, '../assets/js/listlab.js'), 'utf8');
const section = (start, end) => source.slice(source.indexOf(start), source.indexOf(end, source.indexOf(start)));
const categories = [{id:1,name:'Tech'}, {id:2,parent:1,is_tech_child:true,name:'Video > Streaming & Home Media Players'}, {id:3,name:'Art'}];
const schemaData = {categories,tech_category_id:1,tech_subcategories:[categories[1]],attributes:[{taxonomy:'pa_condition',options:[{id:5}]}]};
const state = {schema:schemaData, listing:{categories:[1,2],category_id:1,subcategory_id:2,attributes:{pa_condition:[5]},title:'Retained title',quantity:1},schemaLoading:false};
let schemaFailure = false;
const context = {state, Number, String, stopBarcodeScan(){},scheduleDraftSave(){},renderEditor(){},showToast(){},esc:value=>String(value).replaceAll('&','&amp;'),select:(rows,selected)=>JSON.stringify({rows,selected}), app:{querySelector(){return null;},querySelectorAll(){return []; }},schema:async()=>{if(schemaFailure)throw new Error('Offline'); state.schema=schemaData;} };
context.customAttributePrefix = '__krev_custom__:';
vm.runInNewContext(section('  const select = ', '  const base = ') + section('  function categorySelection(', '  function fields()') + section('  async function changeCategory(', '  async function saveListing(') + '\nthis.selectCategory=categorySelection;this.childField=subcategoryField;this.change=changeCategory;', context);
(async()=>{
  assert.equal(context.selectCategory().parent,1);
  assert.equal(context.selectCategory().child,2);
  assert.equal(context.selectCategory({categories:[2]}).parent,1,'legacy child-only product selects Tech as parent');
  assert.equal(context.selectCategory({categories:[2]}).child,2);
  assert.match(context.childField(state.listing,schemaData),/Tech subcategory/);
  assert.match(context.childField(state.listing,schemaData),/data-field="subcategory_id"/);
  assert.equal(context.childField({categories:[3]},schemaData),'','non-Tech hides the second dropdown');
  await context.change({dataset:{field:'subcategory_id'},value:''});
  assert.equal(state.listing.subcategory_id,0,'clearing subcategory removes stale child');
  assert.equal(state.listing.categories.length,1);
  await context.change({dataset:{field:'subcategory_id'},value:'2'});
  assert.equal(state.listing.categories.join(','),'1,2','selected child keeps parent assignment');
  assert.equal(state.listing.attributes.pa_condition[0],5,'subcategory change preserves inherited condition');
  assert.equal(state.listing.title,'Retained title');
  schemaFailure=true;
  await context.change({dataset:{field:'category_id'},value:'3'});
  assert.equal(state.listing.category_id,1,'failed schema request restores parent');
  assert.equal(state.listing.subcategory_id,2,'failed schema request restores child');
  schemaFailure=false;
  await context.change({dataset:{field:'category_id'},value:'3'});
  assert.equal(state.listing.category_id,3);
  assert.equal(state.listing.subcategory_id,0,'leaving Tech clears the stale Tech selection');
  assert.equal(context.childField(state.listing,schemaData),'');
  console.log('17 Tech selector behavior assertions passed.');
})().catch(error=>{console.error(error);process.exitCode=1;});
