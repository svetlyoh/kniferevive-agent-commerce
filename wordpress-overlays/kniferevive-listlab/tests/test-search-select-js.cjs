const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const { JSDOM } = require(process.env.KREV_JSDOM_PATH || 'jsdom');
const source = fs.readFileSync(require('node:path').join(__dirname, '../assets/js/listlab.js'), 'utf8');
const component = source.slice(source.indexOf('  function searchableSelect('), source.indexOf('  function setupSearchableSelects('));
const dom = new JSDOM('<label>Tech subcategory<select data-field="subcategory_id"><option value="">Select an option</option><option value="325">Computers &gt; Desktop Computers</option><option value="5276">Video &gt; Streaming &amp; Home Media Players</option></select></label><label>Model<select data-attribute="pa_model-number"><option value="">Select an option</option><option value="1">Chromecast Gen 2</option><option value="2">Dell OptiPlex</option><option value="__custom__">+ Add a custom value…</option></select></label>');
const { document, Event, KeyboardEvent } = dom.window;
const context = vm.createContext({ document, Event }); vm.runInContext(component, context);
let assertions = 0;
const check = (a, b) => { assert.deepEqual(a, b); assertions++; };
const category = document.querySelector('[data-field]'); category.value = '5276';
let changes = 0; category.onchange = () => changes++;
context.searchableSelect(category, 'Tech subcategory');
let input = category.parentNode.querySelector('input'), list = category.parentNode.querySelector('[role=listbox]');
const type = value => { input.value = value; input.dispatchEvent(new Event('input')); };
const key = value => input.dispatchEvent(new KeyboardEvent('keydown', { key: value, cancelable: true }));
check(input.value, 'Video > Streaming & Home Media Players');
check(category.hidden, true); check(input.getAttribute('aria-controls'), list.id);
type('desktop computers'); check(list.querySelectorAll('[role=option]').length, 1);
check(category.value, '5276'); // Search text cannot silently change the persisted category.
key('ArrowDown'); check(input.getAttribute('aria-activedescendant'), list.firstChild.id);
key('Enter'); check(category.value, '325'); check(changes, 1); check(list.hidden, true);
type('does not exist'); check(list.textContent, 'No matching options');
key('Enter'); check(category.value, '325');
key('Escape'); check(input.value, 'Computers > Desktop Computers');
category.parentNode.querySelector('button').click(); check(list.querySelectorAll('[role=option]').length, 3);
key('ArrowDown'); key('Enter'); check(category.value, ''); check(input.value, '');
type('stream media'); list.querySelector('[role=option]').click(); check(category.value, '5276');
type('desktop'); input.dispatchEvent(new dom.window.FocusEvent('focusout', { bubbles: true, relatedTarget: document.body }));
check(list.hidden, true); check(input.value, 'Video > Streaming & Home Media Players');
category.disabled = true; type('desktop'); check(list.hidden, true); check(category.value, '5276');
const model = document.querySelector('[data-attribute]');
model.addEventListener('change', () => { if (model.value === '__custom__') { model.add(new dom.window.Option('My model (custom)', 'My model', true, true)); model.dataset.customValue = 'My model'; } });
context.searchableSelect(model, 'Model'); input = model.parentNode.querySelector('input'); list = model.parentNode.querySelector('[role=listbox]');
type('dell'); check(list.querySelectorAll('[role=option]').length, 2);
list.querySelector('[role=option]').click(); check(model.value, '2'); check(input.value, 'Dell OptiPlex');
type('unknown'); check(list.querySelectorAll('[role=option]').length, 1);
key('Enter'); check(model.value, 'My model'); check(input.value, 'My model (custom)');
context.searchableSelect(model, 'Model'); check(document.querySelectorAll('.ll-search-select').length, 2);
console.log(`${assertions} searchable-dropdown assertions passed`);
