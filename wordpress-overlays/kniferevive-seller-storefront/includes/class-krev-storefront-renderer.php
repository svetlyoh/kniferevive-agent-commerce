<?php

defined( 'ABSPATH' ) || exit;

final class KREV_Storefront_Renderer {
	public const META_KEY = '_krev_storefront_config_v1';

	public static function config( int $seller_id ): array {
		$defaults = array(
			'tagline' => '', 'about' => '', 'cover_focal' => '50% 50%', 'style' => 'warm',
			'section_order' => KREV_Storefront_Catalog::SECTION_ORDER,
			'highlighted_brands' => array(), 'highlighted_products' => array(),
			'tech_intro' => 'Practical systems, components, and technology selected for useful second lives.',
			'art_intro' => 'Original work and distinctive pieces presented with clear artist and medium details.',
		);
		$saved = get_user_meta( $seller_id, self::META_KEY, true );
		$saved = is_array( $saved ) ? $saved : array();
		$config = wp_parse_args( $saved, $defaults );
		$order = array_values( array_intersect( array_map( 'sanitize_key', (array) $config['section_order'] ), KREV_Storefront_Catalog::SECTION_ORDER ) );
		$config['section_order'] = array_values( array_unique( array_merge( $order, KREV_Storefront_Catalog::SECTION_ORDER ) ) );
		return $config;
	}

	public static function render( int $seller_id ): void {
		$vendor = dokan()->vendor->get( $seller_id );
		$info = $vendor->get_shop_info();
		$config = self::config( $seller_id );
		$source = KREV_Storefront_Catalog::source_products( $seller_id );
		$brands = KREV_Storefront_Catalog::brands( $source );
		$conditions = KREV_Storefront_Catalog::conditions( $source );
		$filtered = KREV_Storefront_Catalog::filtered( $source );
		$groups = KREV_Storefront_Catalog::group( $filtered );
		$source_groups = KREV_Storefront_Catalog::group( $source );
		$name = trim( (string) ( $info['store_name'] ?? '' ) ) ?: $vendor->get_name();
		$banner_id = absint( $info['banner'] ?? 0 );
		$avatar_id = absint( $info['gravatar'] ?? 0 );
		$cover = self::cover_markup( $banner_id, (string) $config['cover_focal'] );
		$avatar = $avatar_id ? wp_get_attachment_image( $avatar_id, array( 176, 176 ), false, array( 'class' => 'krev-store-avatar', 'loading' => 'eager' ) ) : get_avatar( $seller_id, 176, '', $name, array( 'class' => 'krev-store-avatar' ) );
		$rating = method_exists( $vendor, 'get_rating' ) ? $vendor->get_rating() : array();
		$rating_value = (float) ( $rating['rating'] ?? 0 );
		$rating_count = absint( $rating['count'] ?? 0 );
		$style = in_array( $config['style'], array( 'warm', 'minimal', 'dark' ), true ) ? $config['style'] : 'warm';
		?>
		<div class="krev-seller-storefront krev-store-style--<?php echo esc_attr( $style ); ?>" id="main-content">
			<section class="krev-store-hero" aria-labelledby="krev-store-title">
				<?php echo $cover; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- generated by native image markup with escaped attributes. ?>
				<div class="krev-store-identity">
					<div class="krev-store-avatar-wrap"><?php echo wp_kses_post( $avatar ); ?></div>
					<div class="krev-store-intro"><p class="krev-store-kicker"><?php esc_html_e( 'KnifeRevive Seller', 'kniferevive-seller-storefront' ); ?></p><h1 id="krev-store-title"><?php echo esc_html( $name ); ?></h1>
					<?php if ( $config['tagline'] ) : ?><p class="krev-store-tagline"><?php echo esc_html( $config['tagline'] ); ?></p><?php endif; ?>
					<div class="krev-store-proof"><?php if ( $rating_count ) : ?><span aria-label="<?php echo esc_attr( sprintf( __( '%1$s out of 5 stars from %2$d reviews', 'kniferevive-seller-storefront' ), number_format_i18n( $rating_value, 1 ), $rating_count ) ); ?>"><span aria-hidden="true">★</span> <?php echo esc_html( number_format_i18n( $rating_value, 1 ) ); ?> <small>(<?php echo esc_html( number_format_i18n( $rating_count ) ); ?>)</small></span><?php endif; ?><span><?php echo esc_html( sprintf( _n( '%d active listing', '%d active listings', count( $source ), 'kniferevive-seller-storefront' ), count( $source ) ) ); ?></span></div></div>
					<div class="krev-store-actions"><?php self::contact_action( $source, $seller_id ); ?><?php if ( self::can_edit( $seller_id ) ) : ?><a class="krev-store-button krev-store-button--secondary" href="<?php echo esc_url( add_query_arg( user_can( get_current_user_id(), 'manage_woocommerce' ) ? array( 'seller_id' => $seller_id ) : array(), wc_get_account_endpoint_url( 'storefront' ) ) ); ?>"><?php esc_html_e( 'Customize storefront', 'kniferevive-seller-storefront' ); ?></a><?php endif; ?></div>
					<div class="krev-store-details"><?php do_action( 'kniferevive_storefront_after_actions', $seller_id ); ?></div>
				</div>
				<?php if ( $config['about'] ) : ?><p class="krev-store-about"><?php echo nl2br( esc_html( $config['about'] ) ); ?></p><?php endif; ?>
			</section>

			<?php if ( $source ) : ?>
			<?php self::brand_chips( $brands, $config ); ?>
			<?php self::section_nav( $source_groups ); ?>
			<?php self::filters( $brands, $conditions ); ?>
			<?php endif; ?>

			<div id="krev-store-products" class="krev-store-sections">
			<?php if ( ! $source ) : ?>
                <section class="krev-store-empty" aria-labelledby="krev-store-empty-title">
                    <h2 id="krev-store-empty-title"><?php esc_html_e( 'No active listings right now.', 'kniferevive-seller-storefront' ); ?></h2>
                    <p><?php esc_html_e( 'Check back for new finds from this seller, or explore the marketplace.', 'kniferevive-seller-storefront' ); ?></p>
                    <a class="krev-store-button" href="<?php echo esc_url( home_url( '/shop/' ) ); ?>"><?php esc_html_e( 'Explore the marketplace', 'kniferevive-seller-storefront' ); ?></a>
                </section>
            <?php elseif ( ! $filtered ) : ?><p class="woocommerce-info"><?php esc_html_e( 'No listings match these filters.', 'kniferevive-seller-storefront' ); ?></p><?php endif; ?>
			<?php foreach ( $config['section_order'] as $section ) : if ( empty( $groups[ $section ] ) ) { continue; } self::section( $section, $groups[ $section ], $config ); endforeach; ?>
			</div>
		</div>
		<?php
	}

	/** Decorative cover: native responsive sizes preserve the seller's original. */
	public static function cover_markup( int $banner_id, string $focal ): string {
		if ( ! preg_match( '/^(?:\d{1,3}%|left|center|right) (?:\d{1,3}%|top|center|bottom)$/', $focal ) ) $focal = '50% 50%';
		$image = $banner_id ? wp_get_attachment_image( $banner_id, '1536x1536', false, array(
			'class' => 'krev-store-cover__image', 'alt' => '', 'aria-hidden' => 'true',
			'loading' => 'eager', 'decoding' => 'async', 'fetchpriority' => 'high',
			'sizes' => '(max-width: 760px) calc(100vw - 30px), (max-width: 1320px) 94vw, 1236px',
			'style' => 'object-position:' . $focal . ';',
		) ) : '';
		return '<div class="krev-store-cover' . ( $image ? '' : ' is-fallback' ) . '">' . $image . '</div>';
	}

	private static function can_edit( int $seller_id ): bool {
		return is_user_logged_in() && ( get_current_user_id() === $seller_id || current_user_can( 'manage_woocommerce' ) );
	}

	private static function contact_action( array $products, int $seller_id = 0 ): void {
		if ( function_exists( 'kr_seller_store_contact_markup' ) ) { echo kr_seller_store_contact_markup($seller_id); return; }
		if ( ! $products ) { return; }
		$id = $products[0]->get_id();
		if ( function_exists( 'kniferevive_whatsapp_render_button' ) ) {
			$button = kniferevive_whatsapp_render_button( $id, array( 'label' => __( 'Contact Seller', 'kniferevive-seller-storefront' ), 'class' => 'krev-store-button', 'hide_for_owner' => false, 'show_note' => false ) );
			if ( $button ) { echo $button; return; } // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- escaped shared renderer.
		}
		if ( function_exists( 'kniferevive_telegram_get_url' ) ) {
			$telegram_url = kniferevive_telegram_get_url( $id );
			if ( $telegram_url ) { echo '<a class="krev-store-button" href="' . esc_url( $telegram_url ) . '" target="_blank" rel="noopener noreferrer">' . esc_html__( 'Contact Seller', 'kniferevive-seller-storefront' ) . '</a>'; return; }
		}
		echo '<a class="krev-store-button" href="' . esc_url( $products[0]->get_permalink() . '#tab-seller' ) . '">' . esc_html__( 'Contact Seller', 'kniferevive-seller-storefront' ) . '</a>';
	}

	private static function brand_chips( array $brands, array $config ): void {
		if ( ! $brands ) { return; }
		$highlighted = array_map( 'absint', (array) $config['highlighted_brands'] );
		uasort( $brands, static function ( array $a, array $b ) use ( $highlighted ): int { return (int) in_array( $b['term']->term_id, $highlighted, true ) <=> (int) in_array( $a['term']->term_id, $highlighted, true ); } );
		echo '<nav class="krev-store-brands" aria-label="' . esc_attr__( 'Brands sold by this seller', 'kniferevive-seller-storefront' ) . '"><span>' . esc_html__( 'Shop their brands', 'kniferevive-seller-storefront' ) . '</span><div>';
		foreach ( $brands as $item ) { echo '<a href="' . esc_url( add_query_arg( 'kr_store_brand', $item['term']->slug ) ) . '">' . esc_html( $item['term']->name ) . ' <small>' . absint( $item['count'] ) . '</small></a>'; }
		echo '</div></nav>';
	}

	private static function section_nav( array $groups ): void {
		$labels = self::section_labels();
		echo '<nav class="krev-store-section-nav" aria-label="' . esc_attr__( 'Store sections', 'kniferevive-seller-storefront' ) . '"><a href="#krev-store-products">' . esc_html__( 'All', 'kniferevive-seller-storefront' ) . '</a>';
		foreach ( KREV_Storefront_Catalog::SECTION_ORDER as $section ) { if ( ! empty( $groups[ $section ] ) ) { echo '<a href="#krev-store-' . esc_attr( $section ) . '">' . esc_html( $labels[ $section ] ) . '</a>'; } }
		echo '</nav>';
	}

	private static function filters( array $brands, array $conditions ): void {
		$current = static fn( string $key ): string => isset( $_GET[ $key ] ) ? sanitize_text_field( wp_unslash( $_GET[ $key ] ) ) : '';
		?>
		<form class="krev-store-filters" method="get" action="">
			<label><span><?php esc_html_e( 'Find', 'kniferevive-seller-storefront' ); ?></span><input type="search" name="kr_store_search" value="<?php echo esc_attr( $current( 'kr_store_search' ) ); ?>" placeholder="<?php esc_attr_e( 'Search this store', 'kniferevive-seller-storefront' ); ?>"></label>
			<label><span><?php esc_html_e( 'Section', 'kniferevive-seller-storefront' ); ?></span><select name="kr_store_section"><option value="all"><?php esc_html_e( 'All listings', 'kniferevive-seller-storefront' ); ?></option><?php foreach ( self::section_labels() as $key => $label ) : ?><option value="<?php echo esc_attr( $key ); ?>" <?php selected( $current( 'kr_store_section' ), $key ); ?>><?php echo esc_html( $label ); ?></option><?php endforeach; ?></select></label>
			<label><span><?php esc_html_e( 'Brand', 'kniferevive-seller-storefront' ); ?></span><select name="kr_store_brand"><option value=""><?php esc_html_e( 'All brands', 'kniferevive-seller-storefront' ); ?></option><?php foreach ( $brands as $item ) : ?><option value="<?php echo esc_attr( $item['term']->slug ); ?>" <?php selected( $current( 'kr_store_brand' ), $item['term']->slug ); ?>><?php echo esc_html( $item['term']->name ); ?></option><?php endforeach; ?></select></label>
			<?php if ( $conditions ) : ?><label><span><?php esc_html_e( 'Condition', 'kniferevive-seller-storefront' ); ?></span><select name="kr_store_condition"><option value=""><?php esc_html_e( 'Any condition', 'kniferevive-seller-storefront' ); ?></option><?php foreach ( $conditions as $slug => $name ) : ?><option value="<?php echo esc_attr( $slug ); ?>" <?php selected( $current( 'kr_store_condition' ), $slug ); ?>><?php echo esc_html( $name ); ?></option><?php endforeach; ?></select></label><?php endif; ?>
			<label><span><?php esc_html_e( 'Sort', 'kniferevive-seller-storefront' ); ?></span><select name="kr_store_sort"><option value="newest"><?php esc_html_e( 'Newest', 'kniferevive-seller-storefront' ); ?></option><option value="price-low" <?php selected( $current( 'kr_store_sort' ), 'price-low' ); ?>><?php esc_html_e( 'Price: low to high', 'kniferevive-seller-storefront' ); ?></option><option value="price-high" <?php selected( $current( 'kr_store_sort' ), 'price-high' ); ?>><?php esc_html_e( 'Price: high to low', 'kniferevive-seller-storefront' ); ?></option><option value="name" <?php selected( $current( 'kr_store_sort' ), 'name' ); ?>><?php esc_html_e( 'Name', 'kniferevive-seller-storefront' ); ?></option></select></label>
			<button type="submit"><?php esc_html_e( 'Apply', 'kniferevive-seller-storefront' ); ?></button><a href="<?php echo esc_url( strtok( (string) wp_unslash( $_SERVER['REQUEST_URI'] ?? '' ), '?' ) ); ?>"><?php esc_html_e( 'Clear', 'kniferevive-seller-storefront' ); ?></a>
		</form>
		<?php
	}

	private static function section( string $section, array $products, array $config ): void {
		$labels = self::section_labels();
		$intro = 'technology' === $section ? $config['tech_intro'] : ( 'art' === $section ? $config['art_intro'] : '' );
		$highlighted = array_map( 'absint', (array) $config['highlighted_products'] );
		usort( $products, static function ( WC_Product $a, WC_Product $b ) use ( $highlighted ): int {
			return (int) in_array( $b->get_id(), $highlighted, true ) <=> (int) in_array( $a->get_id(), $highlighted, true );
		} );
		$classes = 'krev-store-section krev-store-section--' . $section;
		echo '<section id="krev-store-' . esc_attr( $section ) . '" class="' . esc_attr( $classes ) . '"><header><div><p class="krev-store-kicker">' . esc_html( sprintf( _n( '%d listing', '%d listings', count( $products ), 'kniferevive-seller-storefront' ), count( $products ) ) ) . '</p><h2>' . esc_html( $labels[ $section ] ) . '</h2>' . ( $intro ? '<p>' . esc_html( $intro ) . '</p>' : '' ) . '</div>';
		if ( 'technology' === $section ) { echo '<a href="' . esc_url( home_url( '/technology-trade-desk/' ) ) . '">' . esc_html__( 'Visit Technology Trade Desk', 'kniferevive-seller-storefront' ) . ' →</a>'; }
		if ( 'art' === $section ) { echo '<a href="' . esc_url( home_url( '/art-trade-gallery/' ) ) . '">' . esc_html__( 'Visit Art Trade Gallery', 'kniferevive-seller-storefront' ) . ' →</a>'; }
		echo '</header><div class="krev-store-grid">';
		foreach ( $products as $product ) { self::card( $product, $section ); }
		echo '</div></section>';
	}

	private static function card( WC_Product $product, string $section ): void {
		if ( 'knives' === $section && function_exists( 'kniferevive_render_knife_card' ) ) {
			echo kniferevive_render_knife_card( $product ); // phpcs:ignore
			return;
		}
		$url = $product->get_permalink();
		$subtitle = trim( (string) $product->get_meta( '_kniferevive_listing_subtitle' ) );
		$brand = function_exists( 'kr_product_brand_markup' ) ? kr_product_brand_markup( $product->get_id(), 'storefront' ) : '';
		echo '<article class="krev-store-card" data-product-id="' . absint( $product->get_id() ) . '"><a class="krev-store-card__image" href="' . esc_url( $url ) . '">' . $product->get_image( 'woocommerce_thumbnail', array( 'loading' => 'lazy', 'decoding' => 'async' ) ) . '</a><div class="krev-store-card__body">';
		if ( $brand ) { echo '<div class="krev-store-card__brand">' . wp_kses_post( $brand ) . '</div>'; }
		echo '<h3><a href="' . esc_url( $url ) . '">' . esc_html( $product->get_name() ) . '</a></h3>';
		if ( $subtitle ) { echo '<p>' . esc_html( $subtitle ) . '</p>'; }
		echo '<div class="krev-store-card__price">' . wp_kses_post( $product->get_price_html() ) . '</div>';
		if (class_exists('\KnifeRevive\Shipping\View')) echo \KnifeRevive\Shipping\View::card($product);
		if ( function_exists( 'kniferevive_render_whatnot_demo_card' ) ) { echo kniferevive_render_whatnot_demo_card( $product ); } // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- helper escapes dynamic output.
		echo '<a class="krev-store-card__link" href="' . esc_url( $url ) . '">' . esc_html__( 'View listing', 'kniferevive-seller-storefront' ) . ' →</a></div></article>';
	}

	private static function section_labels(): array {
		return array( 'technology' => __( 'Technology', 'kniferevive-seller-storefront' ), 'art' => __( 'Art', 'kniferevive-seller-storefront' ), 'knives' => __( 'Knives', 'kniferevive-seller-storefront' ), 'coins' => __( 'World Coins', 'kniferevive-seller-storefront' ), 'spices' => __( 'World Spices', 'kniferevive-seller-storefront' ), 'other' => __( 'Other Finds', 'kniferevive-seller-storefront' ) );
	}
}
